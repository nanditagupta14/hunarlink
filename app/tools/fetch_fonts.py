#!/usr/bin/env python3
"""Download and self-host the site's webfonts.

    python3 tools/fetch_fonts.py        # refresh public/fonts/ + fonts.css

Why
---
index.html used to link a stylesheet from fonts.googleapis.com. That request
was render-blocking on every page load: the browser could not paint text until
a DNS lookup, a TLS handshake and a CSS round trip to a third-party origin had
all finished. Lighthouse costed it at 2,250 ms before first paint.

Self-hosted, those files come from the same origin the document already has a
connection to, can be preloaded, and add no third-party dependency.

What it downloads
-----------------
Only the `latin` and `latin-ext` subsets. The site renders English plus the
rupee sign; the cyrillic, greek and vietnamese ranges Google also serves in the
same request were being fetched and never used.

Google serves these families as variable fonts, so one file covers a whole
weight range and the same URL legitimately appears under several weight
declarations. Files are therefore named by family + weight + style + subset,
and duplicate URLs are collapsed rather than downloaded again.
"""
import os
import re
import sys
import urllib.request

CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Cormorant+Garamond:ital,wght@0,500;0,600;0,700;1,500;1,600"
    "&family=Plus+Jakarta+Sans:wght@400;500;600;700;800"
    "&family=Playfair+Display:wght@600;700"
    "&family=Inter:wght@400;500;600;700;800"
    "&display=swap"
)

# Google only serves woff2 to a browser that advertises it.
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0 Safari/537.36"
)

OUT_DIR = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "public", "fonts"))

HEADER = """/* ==========================================================================
   Self-hosted webfonts
   --------------------------------------------------------------------------
   Generated by tools/fetch_fonts.py from the same Google Fonts request the
   site used to make with a <link> to fonts.googleapis.com.

   Why self-host: that <link> was render-blocking on every page load and the
   audit costed it at 2,250 ms before first paint — the browser could not paint
   text until a DNS lookup, TLS handshake and CSS round trip to a third-party
   origin had all finished. Served from the same origin these files are
   covered by the existing keep-alive connection and can be preloaded.

   Only the `latin` and `latin-ext` subsets are included, which is all the site
   ever renders (English plus the rupee sign). Cyrillic, Greek and Vietnamese
   were being downloaded in the request but never used.
   ========================================================================== */
"""


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    return urllib.request.urlopen(req, timeout=30).read()


def main():
    os.makedirs(OUT_DIR, exist_ok=True)

    raw_css = get(CSS_URL).decode("utf-8")
    blocks = [b for b in raw_css.split("@font-face")[1:] if b.strip()]

    out = [HEADER]
    written = 0
    total = 0
    seen_urls = {}

    for blk in blocks:
        fam = re.search(r"font-family: '([^']+)'", blk)
        weight = re.search(r"font-weight: ([^;]+);", blk)
        style = re.search(r"font-style: (\w+)", blk)
        url = re.search(r"url\((https://[^)]+)\)", blk)
        urange = re.search(r"unicode-range: ([^;]+);", blk)
        if not (fam and weight and url and urange):
            continue

        # Only keep the two subsets the site renders.
        subset = "latin-ext" if "0100" in urange.group(1) else "latin"

        family = fam.group(1)
        wt = weight.group(1).strip()
        st = style.group(1) if style else "normal"

        name = f"{family.replace(' ', '')}-{wt}-{'italic' if st == 'italic' else 'normal'}-{subset}.woff2"
        dest = os.path.join(OUT_DIR, name)

        if name not in seen_urls:
            data = get(url.group(1))
            with open(dest, "wb") as fh:
                fh.write(data)
            seen_urls[name] = url.group(1)
            total += len(data)
            written += 1

        out.append(
            f"""
@font-face {{
  font-family: '{family}';
  font-style: {st};
  font-weight: {wt};
  font-display: swap;
  src: url('/hunarlink/fonts/{name}') format('woff2');
  unicode-range: {urange.group(1).strip()};
}}
"""
        )

    css_path = os.path.join(OUT_DIR, "fonts.css")
    with open(css_path, "w") as fh:
        fh.write("".join(out))

    print(f"wrote {written} font files ({total / 1024:.0f} KB) and {os.path.basename(css_path)}")
    print(f"  into {OUT_DIR}")
    print("  latin subset only is ~631 KB; a first paint loads ~90 KB of it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
